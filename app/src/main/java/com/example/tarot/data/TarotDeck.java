    private static void addSuitCards(List<TarotCard> list, int startId, String suitCn, String suitEn,
                                     String[][] interpretations) {
        String[] cardNames = {"首牌 (Ace)", "二", "三", "四", "五", "六", "七", "八", "九", "十", "侍者", "騎士", "王后", "國王"};
        String[] cardEng = {"Ace", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten", "Page", "Knight", "Queen", "King"};
        String[] reversedDescriptions = getMinorReversedDescriptions(suitCn);
        if (interpretations.length != cardNames.length || reversedDescriptions.length != cardNames.length) {
            throw new IllegalArgumentException("Each tarot suit must define 14 cards: " + suitCn);
        }

        for (int i = 0; i < 14; i++) {
            int id = startId + i;
            String name = suitCn + cardNames[i];
            String engName = cardEng[i] + " of " + suitEn;
            String[] meaning = interpretations[i];
            list.add(new TarotCard(id, name, engName, "小阿爾克那", suitCn,
                    meaning[0], meaning[1], meaning[2], reversedDescriptions[i]));
        }
    }

    /**
     * 隨機洗牌，並為每張牌賦予隨機的正/逆位 (50% 正位 / 50% 逆位)
     */
    public static List<TarotCard> createShuffledDeck() {
        List<TarotCard> allCards = getAllCards();
        List<TarotCard> deck = new ArrayList<>(allCards.size());

        Random random = new Random();
        for (TarotCard original : allCards) {
            TarotCard copy = original.copy();
            copy.setReversed(random.nextBoolean()); // 隨機正/逆位
            deck.add(copy);
        }

        Collections.shuffle(deck, random); // 完全打亂 78 張牌順序
        return deck;
    }
